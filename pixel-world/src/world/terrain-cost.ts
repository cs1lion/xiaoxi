/** 通行代价：让 A* 自己长出「先上大路」的行为，而不是写死巡逻路线。
 *
 * 没有这张表时，小人横穿菜地走直线，看起来像穿模。有了代价，去郊野的路线会
 * 自然先拐上石板路、沿大路出城、再进林子——这是涌现出来的，不是脚本。
 *
 * 数值是「走这一格相当于走几格平地」。草地作为基准 1.0 之外的地形按体感定，
 * 不追求物理意义，只追求路线看起来对。
 */

import type { TerrainId } from './types.ts';

export const WALK_COST: Readonly<Record<TerrainId, number>> = {
  /**
   * 广场砖与石板路要明显便宜，路线才会主动绕上大路。
   *
   * 实测阈值：石板 0.6 以下，绕 3 格去走大路才开始划算；0.8 时直穿草地更便宜，
   * 「先上大路」根本不会出现。取 0.5 而不是方案里的 0.4：0.4 会让走 2.5 格草地
   * 就抵 1 格石板路，小人会为了上大路绕很远，看起来像在绕圈。
   */
  plaza: 0.45,
  stone: 0.5,
  /** 草地：基准。 */
  grass: 1,
  /** 农田：有垄，走起来慢，也避免踩坏庄稼。 */
  farm: 1.4,
  /** 密林：最慢，但可通行（郊野要能走进去）。 */
  tree: 2.5,
};

/**
 * 地形代价。未知地形按草地算：宁可让 A* 慢一点，也不要因为漏配一个地形
 * 而把它当成免费通行，那会让路线直接穿过障碍。
 */
export function walkCostOf(terrain: TerrainId): number {
  return WALK_COST[terrain] ?? WALK_COST.grass;
}
