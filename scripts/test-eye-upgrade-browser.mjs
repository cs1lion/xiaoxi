import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
const output = `eval/avatar/eye-upgrade-ui/${new Date().toISOString().replace(/[:.]/g,'-')}`;
await mkdir(output,{recursive:true});
const browser = await chromium.launch({headless:true,args:process.platform==='win32'?['--use-angle=d3d11']:[]});
const page = await browser.newPage({viewport:{width:1280,height:920},acceptDownloads:true});
const checks=[],errors=[]; page.on('pageerror',error=>errors.push(error.message));
const check=(ok,label)=>{assert.ok(ok,label);checks.push(label)};
const state=()=>page.evaluate(()=>window.__calibrationSnapshot);
async function slider(id,value){await page.locator('#'+id).evaluate((el,value)=>{el.value=value;el.dispatchEvent(new Event('input',{bubbles:true}))},String(value))}
try {
  await page.goto('http://127.0.0.1:8000/static/avatar_lab.html?model=daily-eyes');
  await page.waitForFunction(()=>window.__avatarReady && window.__avatar.svg.getEyeCapabilities().profile==='seed-eyes',{}, {timeout:90000});
  check(await page.evaluate(()=>window.__avatar.svg.getEyeCapabilities().channels.browHeight.pureTranslation),'candidate advertises isolated vertical brow targets');
  await page.locator('#calibrationEnter').click();
  await page.waitForFunction(()=>window.__avatarCalibration?.active);
  const initial=await state();
  await page.selectOption('#calibrationExpression','curious');
  await page.locator('#calibrationBaseline').check();
  const native=await state();
  check(native.pose.browMode==='native' && native.nativeMorphs.eye_brow_up_L===.34 && native.nativeMorphs.neuro_brow_raise_L===0,'curious baseline uses preserved native shapes');
  await page.locator('#calibrationBaseline').uncheck();
  const candidate=await state();
  check(candidate.nativeMorphs.neuro_brow_raise_L===.34 && candidate.nativeMorphs.eye_brow_up_L===0,'candidate routes curious to the new target with no old-shape stacking');
  await page.locator('#calibrationManualBrow').check();
  await slider('calibrationBrowLeft',50); await slider('calibrationBrowRight',0);
  const isolated=await state();
  check(isolated.nativeMorphs.neuro_brow_raise_R===.5 && isolated.nativeMorphs.neuro_brow_raise_L===0,'viewer-left manual control drives the character-right eyebrow');
  await slider('calibrationBlink',100); await slider('calibrationMouth',65); await page.selectOption('#calibrationGaze','right');
  const combined=await state();
  check(combined.expressionWeights.blinkLeft===1 && combined.expressionWeights.blinkRight===1 && combined.params.ParamMouthOpenY===.65 && combined.nativeMorphs.neuro_brow_raise_R===.5,'new brow survives full blink, gaze and speech composition');
  check(combined.fingerprint.id===initial.fingerprint.id,'native/new switching and manual brows preserve frozen registration');
  await page.locator('#calibrationShowRegions').check();
  check(await page.locator('#calibrationRegions polygon').count()===1,'explicit static hair exclusion is displayed with fixed ROI');
  await page.locator('#viewport').screenshot({path:output+'/combined-pose.png'});
  await page.locator('#calibrationExit').click();
  await page.waitForFunction(()=>!window.__avatarCalibration && window.__avatar._raf>0);
  check(await page.evaluate(()=>!window.__avatar.svg.eyeBrowMode || window.__avatar.svg.eyeBrowMode==='calibrated'),'exit restores the ordinary calibrated routing mode');
  await page.evaluate(()=>{window.__probeOriginalFrame=window.__avatar._frame;window.__probeOriginalRender=window.__avatar.svg._state.renderer.render});
  await page.selectOption('#performanceProbeDuration','5');
  await page.locator('#performanceProbeStart').click();
  await page.waitForFunction(()=>window.__avatarPerformanceResult?.stopReason==='duration-complete',{}, {timeout:20000});
  const measured=await page.evaluate(()=>window.__avatarPerformanceResult);
  check(measured.avatarFrames.length>0 && measured.rafIntervalsMs.length>0,'lab measures actual Avatar frames and intervals');
  check(measured.avatarFrames.some(x=>x.render.calls>0),'lab performance includes real render submissions');
  check(await page.evaluate(()=>window.__avatar._frame===window.__probeOriginalFrame && window.__avatar.svg._state.renderer.render===window.__probeOriginalRender),'completed lab probe restores method identities');
  if(measured.measurement.gpu.available)check(measured.gpuFrames.length>0,'available GPU timer returns actual asynchronous samples');
  else check(!!measured.measurement.gpu.reason,'unavailable GPU timer has explicit reason');
  const downloadEvent=page.waitForEvent('download');await page.locator('#performanceProbeExport').click();
  await(await downloadEvent).saveAs(output+'/performance.json');
  check(JSON.parse(await readFile(output+'/performance.json','utf8')).avatarFrames.length===measured.avatarFrames.length,'performance JSON export preserves raw frames');
  await page.selectOption('#performanceProbeDuration','20');await page.locator('#performanceProbeStart').click();
  await page.waitForFunction(()=>window.__avatarPerformanceProbe?.active);
  await page.locator('#performanceProbeStop').click();
  await page.waitForFunction(()=>window.__avatarPerformanceResult?.stopReason==='user-stopped');
  check(await page.locator('#performanceProbeStart').isEnabled(),'early stop restores performance UI');
  await page.locator('#daily').click();
  await page.waitForFunction(()=>window.__avatarReady && window.__avatar.svg.getEyeCapabilities().profile==='seed');
  check(await page.evaluate(()=>window.__avatar.svg.getEyeCapabilities().channels.browHeight.approximate),'original model remains available with truthful capability');
  await page.locator('#dailyEyes').click();
  await page.waitForFunction(()=>window.__avatarReady && window.__avatar.svg.getEyeCapabilities().profile==='seed-eyes');
  await page.setViewportSize({width:430,height:900});
  await page.locator('#calibrationEnter').click();await page.waitForFunction(()=>window.__avatarCalibration?.active);
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'new controls fit mobile width');
  await page.locator('#calibrationExit').click();
  await page.goto('http://127.0.0.1:8000/?avatar=seed-daily-eyes');
  await page.waitForFunction(()=>document.querySelector('#avatarRenderer')?.value==='seed-daily-eyes' && document.querySelector('#avatarRendererStatus')?.textContent.includes('已启用'),{}, {timeout:90000});
  check(await page.locator('#avatarStage canvas').count()===1,'chat entry loads the upgraded candidate');
  check(errors.length===0,`no page errors: ${errors.join(';')}`);
  await writeFile(output+'/results.json',JSON.stringify({ok:true,checks,errors,performanceSummary:measured.summary,environment:measured.environment},null,2));
  console.log(`${checks.length} eye upgrade UI checks passed; ${output}`);
} finally {await browser.close()}
