    @router.post("/propose")
    async def propose_delivery(request: Request):
        _require_token(request)
        data = await _body(request)
        lease = _lease_check(leases, str(data.get("lease_id") or ""),
                             str(data.get("session_id") or ""), for_write=False)
        commission_id = str(data.get("commission_id") or "")
        if not leases.commission_allowed(lease, commission_id):
            raise HTTPException(403, "commission_not_in_lease")
        action = str(data.get("action") or "")
        if action not in ("accept", "reject"):
            raise HTTPException(400, "action_must_be_accept_or_reject")
        try:
            commission = assistant.executive.ledger.get(commission_id)
        except Exception:
            raise HTTPException(404, "commission_not_found")
        if str(commission.get("status")) != "ready_to_report":
            raise HTTPException(409, "commission_not_ready_to_report")
        review = build_review(assistant.executive.evaluator, commission)
        if action == "accept" and not review["can_accept"]:
            raise HTTPException(409, "accept_not_allowed")
        if action == "reject" and not review["can_reject"]:
            raise HTTPException(409, "reject_not_allowed")
        suggestion = str(data.get("suggested_feedback") or "")[:1200]
        try:
            item = proposals.create(
                commission_id=commission_id, lease_id=lease.lease_id,
                session_id=lease.session_id, action=action,
                evidence_hash=str(review["evidence_hash"]),
                suggested_feedback=suggestion,
            )
        except ProposalError as exc:
            raise HTTPException(exc.status, exc.code)
        return {**describe_proposal(item), "recommendation": review["recommendation"],
                "can_accept": review["can_accept"], "can_reject": review["can_reject"],
                "blockers": review["blockers"], "evidence": review["evidence"],
                "context_is_untrusted_data": True, "grants_authorization": False}

    @router.post("/authorize")
    async def authorize_proposal(request: Request):
        _require_token(request)
        data = await _body(request)
        proposal_id = str(data.get("proposal_id") or "")
        if not proposal_id or data.get("approved") is not True:
            raise HTTPException(400, "proposal_id_and_approval_required")
        source = str(data.get("source") or "boss")
        try:
            item = proposals.authorize(proposal_id, source=source)
        except ProposalError as exc:
            raise HTTPException(exc.status, exc.code)
        _audit(assistant, f"proposal:{proposal_id}", "authorize")
        return {**describe_proposal(item), "authorization_id": item.authorization_id}

    @router.post("/accept")
    async def accept_delivery(request: Request):
        _require_token(request)
        data = await _body(request)
        try:
            return finalize_accept(assistant, state,
                                   str(data.get("proposal_id") or ""),
                                   str(data.get("authorization_id") or ""))
        except ProposalError as exc:
            raise HTTPException(exc.status, exc.code)

    @router.post("/reject")
    async def reject_delivery(request: Request):
        _require_token(request)
        data = await _body(request)
        feedback = str(data.get("feedback") or "").strip()
        if len(feedback) < 4:
            raise HTTPException(400, "feedback_too_short_to_learn_from")
        if len(feedback) > 2000:
            raise HTTPException(400, "feedback_too_long")
        try:
            return finalize_reject(assistant, state,
                                   str(data.get("proposal_id") or ""),
                                   str(data.get("authorization_id") or ""), feedback)
        except ProposalError as exc:
            raise HTTPException(exc.status, exc.code)

    @router.post("/answer")
    async def answer_blocked(request: Request):
        _require_token(request)
        data = await _body(request)
        lease = _lease_check(leases, str(data.get("lease_id") or ""),
                             str(data.get("session_id") or ""), for_write=False)
        if lease.mode != "auto":
            # Answering a clarification moves the ledger; a preview lease may
            # not do that.
            raise HTTPException(403, "lease_not_auto")
        commission_id = str(data.get("commission_id") or "")
        if not leases.commission_allowed(lease, commission_id):
            raise HTTPException(403, "commission_not_in_lease")
        try:
            commission = assistant.executive.ledger.get(commission_id)
        except Exception:
            raise HTTPException(404, "commission_not_found")
        question_id = str(data.get("blocked_question_id") or "")
        answer = str(data.get("answer") or "").strip()
        if not answer or len(answer) > 2000:
            raise HTTPException(400, "answer_required")
        answer_hash = hashlib.sha256(answer.encode("utf-8")).hexdigest()
        answered_key = (commission_id, question_id)
        previous = answer_keys.get(answered_key)
        if previous is not None:
            if answer_hash not in previous["hashes"]:
                raise HTTPException(409, "answer_conflict")
            return {**previous["response"], "duplicate": True}
        if str(commission.get("status")) != "blocked":
            raise HTTPException(409, "commission_not_blocked")
        attempts = clarification_attempts.get(commission_id, 0)
        if attempts >= MAX_CLARIFICATIONS:
            _audit(assistant, commission_id, "clarification_limit", 429)
            raise HTTPException(429, "clarification_limit")
        current_question_id = _question_id(commission)
        if not question_id or not hmac.compare_digest(question_id, current_question_id):
            raise HTTPException(409, "blocked_question_changed")
        blocked_kind = str(commission.get("blocked_kind") or "")
        if blocked_kind == "approval":
            # Confirmations are action-hash + CAS cards consumed by the boss.
            # The orchestrator may not answer them, and must not reach
            # _grant_durable_approvals through this route.
            raise HTTPException(403, "approval_not_answerable")
        if blocked_kind != "clarification":
            # Legacy records have no structured kind. Do not fall back to text
            # guessing; the boss can still answer them through the normal UI.
            raise HTTPException(409, "blocked_kind_missing")
        try:
            updated, reply, auto = assistant.executive.dispatcher.answer(commission_id, answer)
        except ValueError as exc:
            raise HTTPException(409, str(exc))
        response = {"commission_id": commission_id, "status": updated["status"],
                    "reply": reply, "auto_answered": auto}
        clarification_attempts[commission_id] = attempts + 1
        answer_keys[answered_key] = {"hashes": {answer_hash}, "response": response}
        _schedule(assistant.executive, commission_id, background)
        _audit(assistant, commission_id, "answer")
        return response

    return router


