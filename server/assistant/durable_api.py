"""Read-only host API for the durable sidecar (C1).

The sidecar's Agent may look at memory, notes, threads, and the worker roster,
but it must not write the ledger. Every route here is a read; the token is
generated by the host at sidecar startup and passed via XIAOXI_HOST_TOKEN.

The durable tools call these routes as local loopback HTTP. They are not part of
PROTOCOL.md: the browser never sees them, and Python remains the only writer.
"""
