    @router.post("/orchestrator")
    async def start_orchestrator(request: Request):
        _require_token(request)
        data = await _body(request)
        session_id = str(data.get("session_id") or "").strip()
        prompt = str(data.get("prompt") or "").strip()
        if not session_id or not prompt:
            raise HTTPException(400, "session_id_and_prompt_required")
        if runtime_provider is None:
            raise HTTPException(503, "durable_runtime_unavailable")
        runtime = runtime_provider()
        if not runtime or not runtime.get("endpoint"):
            raise HTTPException(503, "durable_runtime_unavailable")
        lease = leases.issue(session_id, prompt, data.get("mode"))
        commission_id = f"orchestrator:{session_id}:{uuid.uuid4().hex[:12]}"
        payload = {
            "commission_id": commission_id,
            "agent_id": "orchestrator",
            "profile": "orchestrator",
            "lease_id": lease["lease_id"],
            "session_id": session_id,
            "packet": {"objective": prompt, "prompt": prompt},
        }
        headers = {"content-type": "application/json"}
        token = runtime.get("token")
        if token:
            headers["authorization"] = f"Bearer {token}"
        try:
            async with httpx.AsyncClient(timeout=30.0) as client:
                created = await client.post(f"{runtime['endpoint']}/v1/runs",
                                            headers=headers, json=payload)
        except Exception:
            raise HTTPException(502, "durable_runtime_unreachable")
        if created.status_code >= 400:
            raise HTTPException(502, "durable_runtime_rejected")
        _audit(assistant, commission_id, "orchestrator_start")
        return {**created.json(), "lease_id": lease["lease_id"], "mode": lease["mode"]}

