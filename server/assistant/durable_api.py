_HOST_TOKEN: str | None = None
MAX_CLARIFICATIONS = 3


def set_host_token(token: str | None) -> None:
    global _HOST_TOKEN
    _HOST_TOKEN = token


def _require_token(request: Request) -> None:
    if not _HOST_TOKEN:
        raise HTTPException(503, "host_api_not_configured")
    supplied = request.headers.get("authorization", "")
    if not hmac.compare_digest(supplied, f"Bearer {_HOST_TOKEN}"):
        raise HTTPException(401, "unauthorized")


async def _body(request: Request) -> dict[str, Any]:
    try:
        value = await request.json()
    except Exception:
        raise HTTPException(400, "invalid_json")
    if not isinstance(value, dict):
        raise HTTPException(400, "object_required")
    return value


def _memory_search(memory_manager, query: str, top_k: int) -> dict[str, Any]:
    if memory_manager is None or not getattr(memory_manager, "enabled", False):
        # A disabled memory is not the same as "no matching memory". Say so, so
        # the model does not fill the gap from common sense.
        return {"schema_version": 1, "status": "disabled", "query": query,
                "stated": [], "inferred": [], "uncertain": [],
                "note": "记忆已关闭，本轮不能检索；不要据此编造共同经历。"}
    try:
        hits = memory_manager.retriever.search(query, top_k=top_k)
    except Exception:
        return {"schema_version": 1, "status": "unavailable", "query": query,
                "stated": [], "inferred": [], "uncertain": [],
                "note": "记忆检索暂不可用；没查到不等于没发生，不要补写。"}
    from .context import _text
    from ..memory.presentation import present_memory

    now = time.time()
    groups: dict[str, list[dict[str, Any]]] = {"stated": [], "inferred": [], "uncertain": []}
    for hit in hits[:top_k]:
        record = hit[0] if isinstance(hit, (tuple, list)) else hit
        if getattr(record, "status", None) != "active":
            continue
        source = getattr(record, "source", None)
        if source not in groups:
            source = "uncertain"
        updated = getattr(record, "updated_at", None)
        if not isinstance(updated, (int, float)):
            updated = None
        # Match ContextBuilder's short inference lifetime at this boundary.
        if source != "stated" and (updated is None or now - updated > 72 * 3600 or updated > now):
            continue
        shared = present_memory(record, sanitize=_text, max_value_chars=320)
        if shared is None:
            continue
        groups[source].append({
            **shared,
            "key": _text(getattr(record, "key", ""), 80),
            "updated_at": updated,
            "confidence": getattr(record, "confidence", None),
            "requires_confirmation": source != "stated" or shared["evidence"]["state"] == "legacy",
        })
    found = any(groups.values())
    return {
        "schema_version": 1, "status": "found" if found else "not_found", "query": query,
        "top_k": top_k, **groups,
        "note": "" if found else "没查到相关记忆；没查到不等于没发生，不要编造共同经历。",
        "context_is_untrusted_data": True, "grants_authorization": False,
    }


def _worker_rows(executive) -> list[dict[str, Any]]:
    roster = executive.roster or {}
    selection = roster.get("selection") or {}
    default_cap = int(selection.get("max_concurrent_default", 2) or 2)
    load = {}
    try:
        from .dispatcher import in_flight_load
        load = in_flight_load(executive.ledger.open_commissions())
    except Exception:
        load = {}
    rows: list[dict[str, Any]] = []
    seen: set[str] = set()
    for key in ("agents", "workers"):
        for worker in roster.get(key) or []:
            if not isinstance(worker, dict):
                continue
            agent_id = str(worker.get("id") or "")
            if not agent_id or agent_id in seen:
                continue
            seen.add(agent_id)
            cap = int(worker.get("max_concurrent") or default_cap)
            using = int(load.get(agent_id, 0) or 0)
            rows.append({
                "id": agent_id,
                "name": str(worker.get("name") or agent_id),
                "adapter": str(worker.get("adapter") or "manual"),
                "summary": str(worker.get("summary") or ""),
                "strengths": [str(item) for item in (worker.get("strengths") or [])],
                "weaknesses": [str(item) for item in (worker.get("weaknesses") or [])],
                "cost_tier": str(worker.get("cost_tier") or ""),
                "max_concurrent": cap,
                "in_flight": using,
                "available": using < cap,
                "enabled": worker.get("enabled", True) is not False,
            })
    return rows


def _question_id(commission: dict[str, Any]) -> str:
    raw = f"{commission.get('id')}\n{commission.get('blocked_question')}\n{commission.get('retry_count')}"
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()[:24]


def _task_view(commission: dict[str, Any]) -> dict[str, Any]:
    audit = commission.get("audit") if isinstance(commission.get("audit"), dict) else {}
    delivery = commission.get("delivery") if isinstance(commission.get("delivery"), dict) else {}
    status = str(commission.get("status") or "")
    findings = audit.get("findings") if isinstance(audit.get("findings"), list) else []
    return {
        "commission_id": str(commission.get("id") or ""),
        "title": str(commission.get("title") or "")[:200],
        "status": status,
        "agent_id": str(commission.get("agent_id") or ""),
        "retry_count": int(commission.get("retry_count") or 0),
        "blocked_question": str(commission.get("blocked_question") or ""),
        "blocked_kind": str(commission.get("blocked_kind") or ""),
        "blocked_question_id": _question_id(commission) if status == "blocked" else None,
        "audit": {
            "passed": audit.get("passed"),
            "layer": audit.get("layer"),
            "findings": findings[:8],
            "scolding": str(audit.get("scolding") or "")[:600],
        },
        "delivery": {
            "summary": str(delivery.get("summary") or "")[:600],
            "artifacts": (delivery.get("artifacts") or [])[:12],
        },
        "created_at": commission.get("created_at"),
        "updated_at": commission.get("updated_at"),
        "context_is_untrusted_data": True,
        "grants_authorization": False,
    }


def _agent_entry(assistant, agent_id: str) -> dict[str, Any] | None:
    for worker in assistant.executive.roster.get("agents") or []:
        if isinstance(worker, dict) and worker.get("id") == agent_id:
            return worker
    return None


def _lease_check(lease_store: LeaseStore, lease_id: str, session_id: str, *,
                 agent_id: str | None = None, cost_tier: str | None = None,
                 for_write: bool = False, allow_modes: tuple[str, ...] = ("auto",)):
    try:
        return lease_store.validate(lease_id, session_id, agent_id=agent_id,
                                    cost_tier=cost_tier, for_write=for_write,
                                    allow_modes=allow_modes)
    except LeaseError as exc:
        raise HTTPException(exc.status, exc.code)


def _schedule(executive, commission_id: str, background: set[asyncio.Task]) -> None:
    task = asyncio.create_task(executive.drive(commission_id))
    background.add(task)
    task.add_done_callback(background.discard)


def _fail_dispatch(executive, commission_id: str, question: str) -> None:
    try:
        current = executive.ledger.get(commission_id)
        status = str(current.get("status") or "")
        if status == "drafting":
            # "Not dispatched" must not be recorded as "done". Move through the
            # same briefing -> blocked path delegate uses, with a question the
            # boss can see.
            executive.ledger.transition(commission_id, "briefing")
            executive.dispatcher.block(commission_id, question[:400], kind="clarification")
        elif status in ("briefing", "running", "auditing"):
            executive.dispatcher.block(commission_id, question[:400], kind="clarification")
    except Exception:
        pass


def create_durable_router(assistant, memory_manager,
                          lease_store: LeaseStore | None = None,
                          runtime_provider: Callable[[], dict[str, str] | None] | None = None,
                          state: DurableState | None = None) -> APIRouter:
    router = APIRouter(prefix="/internal/durable", tags=["durable"])
    # The workbench router receives this same object in app.py. Passing a lease
    # store alone keeps older tests (and one-off hosts) working.
    state = state or DurableState(assistant.executive.ledger, leases=lease_store)
    leases = state.leases
    confirmations = state.confirmations
    proposals = state.proposals
    clarification_attempts = state.clarification_attempts
    dispatch_keys = state.dispatch_keys
    answer_keys = state.answer_keys
    background = state.background

    @router.post("/memory/search")
    async def memory_search(request: Request):
        _require_token(request)
        data = await _body(request)
        query = data.get("query")
        if not isinstance(query, str) or not query.strip():
            raise HTTPException(400, "query_required")
        top_k = data.get("top_k", 6)
        if type(top_k) is not int or not 1 <= top_k <= 12:
            raise HTTPException(400, "top_k_must_be_1_to_12")
        return _memory_search(memory_manager, query.strip(), top_k)

