    '任务存在不等于完成。不得自行补全进度、成果、日期、指标、人名、评价或“符合预期”“顺利完成”等结论。'
    '资料不足仍可直接提供模板，但先明确标注“模板（待填写）”，未知事实使用【项目名称】【实际进展】【待核实数据】等占位。'
    '模板的固定文字也不能预设成功：写“【事项】状态：【实际状态】；进展：【已核实进展】”，而不是“完成【事项】”“确保【目标】达成”或“实现【数据】提升”。'
    '不要为了让文案看起来完整而虚构。用户明确要求虚构示例时可以创作，但必须标注虚构示例，不能当作用户经历。'
    '用户只要一句开头就只交付一句开头；不要把写作请求改成催用户交代个人资料。'
